#!/usr/bin/env node
/* eslint-env node */
'use strict';

/**
 * Generates src/config/build.env.js from apps/mobile/.env.
 *
 * React Native has no runtime process.env. This script keeps the mobile
 * build-time configuration explicit and testable without adding a native
 * configuration dependency.
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const ENV_FILE = path.join(ROOT, '.env');
const TARGET = path.join(ROOT, 'src', 'config', 'build.env.js');

const DEFAULTS = {
  VIBESYNC_API_URL: 'https://api.vibesync.app',
  VIBESYNC_DEV_HOST: '',
  VIBESYNC_WEB_URL: 'https://vibesync.app',
  VIBESYNC_APP_SCHEME: 'vibesync',
};

function parseEnv(source) {
  const values = {};
  for (const rawLine of source.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const separator = line.indexOf('=');
    if (separator === -1) continue;
    const key = line.slice(0, separator).trim();
    let value = line.slice(separator + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    values[key] = value;
  }
  return values;
}

function validate(values) {
  const errors = [];
  for (const key of ['VIBESYNC_API_URL', 'VIBESYNC_WEB_URL']) {
    if (!values[key]) continue;
    try {
      const parsed = new URL(values[key]);
      if (!['http:', 'https:'].includes(parsed.protocol)) {
        errors.push(`${key} must use http:// or https://`);
      }
    } catch {
      errors.push(`${key} is not a valid URL`);
    }
  }
  const host = values.VIBESYNC_DEV_HOST;
  if (host && /[/:?#\s]/.test(host)) {
    errors.push('VIBESYNC_DEV_HOST must be a hostname or IP address without a scheme or port');
  }
  if (values.VIBESYNC_APP_SCHEME && !/^[a-z][a-z0-9+.-]*$/i.test(values.VIBESYNC_APP_SCHEME)) {
    errors.push('VIBESYNC_APP_SCHEME must be a valid URL scheme');
  }
  return errors;
}

function main() {
  let values = { ...DEFAULTS };
  if (fs.existsSync(ENV_FILE)) {
    values = { ...values, ...parseEnv(fs.readFileSync(ENV_FILE, 'utf8')) };
  } else {
    process.stdout.write('No apps/mobile/.env found; writing default build configuration.\n');
  }

  for (const key of Object.keys(DEFAULTS)) {
    if (process.env[key] !== undefined) values[key] = process.env[key];
  }
  const production = process.argv.includes('--production');

  const errors = validate(values);
  if (production) {
    for (const key of ['VIBESYNC_API_URL', 'VIBESYNC_WEB_URL']) {
      if (!values[key].startsWith('https://')) errors.push(`${key} must use HTTPS for a release build`);
    }
    values.VIBESYNC_DEV_HOST = '';
  }
  if (errors.length) {
    for (const error of errors) process.stderr.write(`Configuration error: ${error}\n`);
    process.exitCode = 1;
    return;
  }

  const output = `// Generated by scripts/apply-env.js. Do not edit by hand.\n// Source: apps/mobile/.env (see .env.example).\nexport default ${JSON.stringify(
    {
      apiUrl: values.VIBESYNC_API_URL,
      devHost: values.VIBESYNC_DEV_HOST,
      webUrl: values.VIBESYNC_WEB_URL,
      appScheme: values.VIBESYNC_APP_SCHEME,
    },
    null,
    2,
  )};\n`;

  fs.mkdirSync(path.dirname(TARGET), { recursive: true });
  fs.writeFileSync(TARGET, output, 'utf8');
  process.stdout.write('Wrote src/config/build.env.js\n');
}

main();
